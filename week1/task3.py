# Convert an integer to a floating-point number
i = 5
f = float(i)
print("Integer to float:", f, "- Type:", type(f))

# Convert a floating-point number to an integer
f2 = 7.9
i2 = int(f2)
print("Float to integer:", i2, "- Type:", type(i2))

# Convert an integer to a string
i3 = 42
s = str(i3)
print("Integer to string:", s, "- Type:", type(s))

# Convert a string containing a number to an integer
s2 = "123"
i4 = int(s2)
print("String to integer:", i4, "- Type:", type(i4))

# Convert an integer to a boolean
i5 = 0
b = bool(i5)
print("Integer to boolean:", b, "- Type:", type(b))